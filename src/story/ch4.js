// ---------------------------------------------------------------- helpers
// background per-frame hook; return true from fn to stop it (it is cleaned up with the mission)
function every(m, fn) { m.waitFor((dt) => fn(dt) === true).catch(() => { }); }
// mission clock (m.t is internal)
function clockOf(m) { const c = { t: 0 }; every(m, (dt) => { c.t += dt; }); return c; }
// dialogue that plays while the player keeps control; chained so lines never overlap
function chatter(m) {
  let p = Promise.resolve();
  return { say(ids) { p = p.then(() => m.talk(ids)).catch(() => { }); return p; }, done() { return p; } };
}
// a point d metres along a road point's heading (negative = behind)
const along = (p, d, side = 0) => ({ x: p.x + Math.cos(p.h) * d - Math.sin(p.h) * side, y: p.y + Math.sin(p.h) * d + Math.cos(p.h) * side, h: p.h });
// first road lane point found around `pos` at one of the given offsets
function laneNear(m, pos, offsets) {
  const c = m.place(pos);
  for (const [dx, dy] of offsets) {
    const r = m.roadAt({ x: c.x + dx, y: c.y + dy }, { lane: true });
    if (r.road) return r;
  }
  return m.roadAt(c, { lane: true, maxD: 300 });
}
// a road lane point roughly `d` metres behind the player (tries a few angles)
function behindPlayer(m, d) {
  const e = m.vehicle || m.ped;
  const h = m.vehicle ? m.vehicle.h : (e.h || 0);
  for (const a of [0, 0.5, -0.5, 1, -1, Math.PI]) {
    const r = m.roadAt({ x: e.x - Math.cos(h + a) * d, y: e.y - Math.sin(h + a) * d }, { lane: true });
    if (r.road && m.dist(r) > d * 0.6) return r;
  }
  return m.roadAt({ x: e.x - Math.cos(h) * d, y: e.y - Math.sin(h) * d }, { lane: true, maxD: 300 });
}
// wait until the player is driving `v` (m.enterVehicle keeps a fail-if-destroyed check for the whole mission)
async function board(m, v, label) {
  if (label) m.objective(label);
  v.blip = v.blip || '#4af';
  const stop = m.failIf(() => (v.dead || v.sunk) && m.vehicle !== v, 'The car was wrecked before you got in.');
  await m.waitFor(() => m.vehicle === v);
  stop();
  v.blip = null;
}
// keep AI cars chasing the player (m.pursue only snapshots the target position)
function hunt(m, cars) {
  let on = true, t = 0;
  every(m, (dt) => {
    if (!on) return true;
    if ((t -= dt) > 0) return false;
    t = 0.25;
    const T = m.vehicle || m.ped;
    for (const v of cars) if (!v.dead && !v._bailed && v.ai && v.driver && !v.driver.dead) m.pursue(v, T);
    return false;
  });
  return () => { on = false; for (const v of cars) if (v.ai && !v.dead) m.driveTo(v, { x: v.x + 3000, y: v.y - 3000 }, { flee: true, speed: 20 }); };
}
// NPCs can't shoot from cars, so a hit car that stalls next to Polly (or finds her on foot) unloads its gunmen
function bailers(m, cars, out, o = {}) {
  let on = true;
  every(m, (dt) => {
    if (!on) return true;
    for (const v of cars) {
      if (v.dead || v._bailed || !v.driver || v.driver.dead) continue;
      const d = m.dist(v);
      const stalled = d < 24 && v.speed < 3 && (!m.vehicle || m.vehicle.speed < 5);
      v._stall = stalled || (!m.vehicle && d < 30) ? (v._stall || 0) + dt : 0;
      if (v._stall > 1.2) {
        v._bailed = true;
        if (v.ai) v.ai.mode = 'stop';
        const r = m.roadAt(v);
        out.push(...m.gang(o.n || 2, { x: (v.x + r.x) / 2, y: (v.y + r.y) / 2 }, { weapon: o.weapon || 'pistol', models: ['gusher'], spread: 2, faction: 'syndicate', health: o.health || 70, blip: '#e33' }));
      }
    }
    return false;
  });
  return () => { on = false; };
}
// tail a car without being spotted or losing it, until done(seconds, distance) says so
async function tail(m, v, o) {
  let close = 0, t = 0;
  const stop = m.failIf(() => v.dead, 'The target was destroyed.');
  if (o.label) m.objective(o.label);
  v.blip = v.blip || '#4af';
  await m.waitFor((dt) => {
    t += dt;
    const d = m.dist(v);
    if (d > o.maxDist) m.fail(o.lostMsg);
    // grace period while the target pulls away from the start
    close = d < o.minDist && t > 8 ? close + dt : Math.max(0, close - dt);
    if (close > o.spotTime) m.fail(o.spottedMsg);
    m.bar('SUSPICION', Math.min(1, close / o.spotTime), '#e8b030');
    return o.done(t, d);
  });
  stop();
  v.blip = null;
  m.clearBar();
}
// resolves once every live threat has been more than `far` metres away for `hold` seconds
async function shake(m, cars, peds, o = {}) {
  const far = o.far || 200, hold = o.hold || 3;
  if (o.label) m.objective(o.label);
  let t = 0;
  await m.waitFor((dt) => {
    const live = cars.filter((v) => !v.dead && !v._bailed && v.driver && !v.driver.dead);
    const near = [...live, ...peds.filter((p) => !p.dead)].some((e) => m.dist(e) < far);
    t = near ? Math.max(0, t - dt * 2) : t + dt;
    m.bar(o.bar || 'LOSING THEM', Math.min(1, t / hold), '#7ed36b');
    return t >= hold;
  });
  m.clearBar();
}
// drive an AI car through waypoints. The road router is greedy and commits to its next turn ~40 m ahead,
// so each waypoint sits just past a corner, on the road it should turn onto.
function route(m, v, pts, speed, r = 20) {
  let i = 0;
  m.driveTo(v, pts[0], { speed });
  every(m, () => {
    if (v.dead || !v.ai) return true;
    if (m.dist(v, pts[i]) > r) return false;
    if (++i >= pts.length) return true;
    m.driveTo(v, pts[i], { speed });
    return false;
  });
}
