#!/usr/bin/env python3
"""Extract tower locations and surveyed diameters from the regional OpenStreetMap PBF."""
import argparse
import json
import math
from pathlib import Path

import osmium
from shapely.geometry import Point, Polygon

ROOT = Path(__file__).resolve().parents[1]


def main(path):
    meta = json.loads((ROOT / 'assets/map/meta.json').read_text())
    origin = meta['origin']
    region = [Polygon(p) for p in meta['world']]
    rows = []
    for item in osmium.FileProcessor(str(path)).with_locations():
        if item.tags.get('man_made') != 'water_tower':
            continue
        diameter = None
        if item.is_node():
            lat, lon = item.location.lat, item.location.lon
        elif item.is_way() and item.is_closed():
            polygon = Polygon([(n.lon, n.lat) for n in item.nodes])
            lon, lat = polygon.centroid.coords[0]
            diameter = round(math.sqrt(polygon.area * origin['kx'] * origin['ky'] * 4 / math.pi), 1)
        else:
            continue
        p = Point((lon - origin['lon']) * origin['kx'], (origin['lat'] - lat) * origin['ky'])
        if not any(poly.covers(p) for poly in region):
            continue
        height = item.tags.get('height', '').removesuffix(' m')
        rows.append([f'{item.type_str()}{item.id}', round(lat, 7), round(lon, 7), diameter,
                     float(height) if height.replace('.', '', 1).isdigit() else None])
    out = ROOT / 'src/data/water-towers.js'
    out.write_text('// OpenStreetMap water towers, generated by tools/import_water_towers.py.\n'
                   '// [source object, latitude, longitude, footprint diameter in metres, tagged height in metres]\n'
                   + 'export const waterTowers = [\n'
                   + ''.join('  ' + json.dumps(row) + ',\n' for row in rows) + '];\n')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('pbf', type=Path)
    main(parser.parse_args().pbf)
